window.findSahayAnswer = function(query, lang = 'en', userProfile = {}) {
  if (!query || !query.trim()) return null;
  const q = query.toLowerCase().trim();
  const isHindi = lang === 'hi' || /[\u0900-\u097F]/.test(query);

  let bestMatch = null;
  let highestScore = 0;

  for (const item of window.SAHAY_KNOWLEDGE_BASE) {
    let score = 0;
    const qEn = item.question_en.toLowerCase();
    const qHi = item.question_hi.toLowerCase();

    // Exact question match
    if (q === qEn || q === qHi) score += 100;
    if (q.includes(qEn) || qEn.includes(q)) score += 60;
    if (isHindi && (q.includes(qHi) || qHi.includes(q))) score += 70;

    // Keyword matches
    for (const kw of item.keywords) {
      const lowerKw = kw.toLowerCase();
      if (q === lowerKw) score += 40;
      else if (q.includes(lowerKw)) score += 25;
    }

    // Token overlap
    const tokens = q.split(/\s+/).filter(t => t.length > 2);
    for (const token of tokens) {
      if (qEn.includes(token)) score += 10;
      if (qHi.includes(token)) score += 10;
      if (item.category.includes(token)) score += 8;
    }

    if (score > highestScore) {
      highestScore = score;
      bestMatch = item;
    }
  }

  // Minimum threshold to consider a solid match
  if (highestScore >= 20 && bestMatch) {
    const replyText = isHindi ? bestMatch.answer_hi : bestMatch.answer_en;
    return {
      match: bestMatch,
      reply: replyText,
      language: isHindi ? 'hi' : 'en',
      citations: bestMatch.citations,
      suggestedChips: bestMatch.suggestedChips,
      score: highestScore
    };
  }

  return null;
};
